CREATE OR REPLACE FUNCTION public.hu002_comprobar_series(p_motor text, p_chasis text, p_excluir bigint DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE existente public.unidad%ROWTYPE; campo text; llave bigint;
BEGIN
  -- Orden determinista; los índices únicos protegen incluso escrituras fuera del RPC.
  FOR llave IN SELECT DISTINCT k FROM (VALUES
    (pg_catalog.hashtextextended('motor:'||public.hu002_normalizar(p_motor),2)),
    (pg_catalog.hashtextextended('chasis:'||public.hu002_normalizar(p_chasis),2))) AS claves(k) ORDER BY k
  LOOP PERFORM pg_catalog.pg_advisory_xact_lock(llave); END LOOP;
  SELECT * INTO existente FROM public.unidad WHERE public.hu002_normalizar(nummotuni)=public.hu002_normalizar(p_motor)
    AND (p_excluir IS NULL OR coduni<>p_excluir);
  campo := 'nummotuni';
  IF NOT FOUND THEN
    SELECT * INTO existente FROM public.unidad WHERE public.hu002_normalizar(chauni)=public.hu002_normalizar(p_chasis)
      AND (p_excluir IS NULL OR coduni<>p_excluir);
    campo := 'chauni';
  END IF;
  IF FOUND THEN
    RAISE EXCEPTION USING ERRCODE='PT409', MESSAGE='Serie duplicada',
      DETAIL=jsonb_build_object('campo',campo,'unidad',public.hu002_proyeccion_unidad(existente))::text;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.hu002_guardar_unidad()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE compra public.compra%ROWTYPE; usadas bigint;
BEGIN
  IF TG_OP='DELETE' THEN
    PERFORM 1 FROM public.compra WHERE codcom=OLD.codcom FOR UPDATE;
    RETURN OLD;
  END IF;
  IF TG_OP='UPDATE' AND NEW.codcom IS DISTINCT FROM OLD.codcom THEN
    RAISE EXCEPTION USING ERRCODE='PT411', MESSAGE='La ficha debe permanecer en la compra original';
  END IF;
  SELECT * INTO compra FROM public.compra WHERE codcom=NEW.codcom FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Compra inexistente'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.factura_compra WHERE codcom=NEW.codcom) THEN
    RAISE EXCEPTION USING ERRCODE='PT410', MESSAGE='Factura no registrada';
  END IF;
  IF EXISTS (SELECT 1 FROM public.factura_compra WHERE codcom=NEW.codcom AND cantidad_motos<>compra.cancom)
    OR NEW.codmod IS DISTINCT FROM compra.codmod OR public.hu002_normalizar(NEW.coluni) IS DISTINCT FROM public.hu002_normalizar(compra.colcom) THEN
    RAISE EXCEPTION USING ERRCODE='PT411', MESSAGE='Discrepancia de factura, modelo o color';
  END IF;
  NEW.nummotuni := public.hu002_normalizar(NEW.nummotuni);
  NEW.chauni := public.hu002_normalizar(NEW.chauni);
  IF coalesce(NEW.nummotuni,'')='' OR coalesce(NEW.chauni,'')='' OR coalesce(public.hu002_normalizar(NEW.coluni),'')='' THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Motor, chasis y color son obligatorios';
  END IF;
  PERFORM public.hu002_comprobar_series(NEW.nummotuni,NEW.chauni,CASE WHEN TG_OP='UPDATE' THEN OLD.coduni ELSE NULL END);
  SELECT count(*) INTO usadas FROM public.unidad WHERE codcom=NEW.codcom AND coduni<>NEW.coduni;
  IF usadas>=compra.cancom THEN RAISE EXCEPTION USING ERRCODE='PT412', MESSAGE='Cantidad de compra excedida'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS hu002_guardar_unidad ON public.unidad;
CREATE TRIGGER hu002_guardar_unidad BEFORE INSERT OR DELETE OR UPDATE OF codcom,codmod,nummotuni,chauni,coluni ON public.unidad
FOR EACH ROW EXECUTE FUNCTION public.hu002_guardar_unidad();

CREATE OR REPLACE FUNCTION public.hu002_guardar_compra()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE identificadas bigint; factura boolean;
BEGIN
  SELECT count(*) INTO identificadas FROM public.unidad WHERE codcom=OLD.codcom;
  IF NEW.cancom<identificadas THEN RAISE EXCEPTION USING ERRCODE='PT412', MESSAGE='Cantidad menor a unidades existentes'; END IF;
  SELECT EXISTS(SELECT 1 FROM public.factura_compra WHERE codcom=OLD.codcom) INTO factura;
  IF (factura OR identificadas>0) AND (NEW.codmod IS DISTINCT FROM OLD.codmod OR NEW.colcom IS DISTINCT FROM OLD.colcom OR NEW.cancom IS DISTINCT FROM OLD.cancom) THEN
    RAISE EXCEPTION USING ERRCODE='PT411', MESSAGE='La compra con factura o unidades requiere revisión antes de cambiar datos originales';
  END IF;
  IF factura THEN
    NEW.estcom := CASE WHEN identificadas=NEW.cancom THEN 'Identificada' ELSE 'Pendiente de identificación' END;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS hu002_guardar_compra ON public.compra;
CREATE TRIGGER hu002_guardar_compra BEFORE UPDATE OF codmod,colcom,cancom,estcom ON public.compra
FOR EACH ROW EXECUTE FUNCTION public.hu002_guardar_compra();

CREATE OR REPLACE FUNCTION public.hu002_actualizar_estado()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE compra_id bigint;
BEGIN
  compra_id := CASE WHEN TG_OP='DELETE' THEN OLD.codcom ELSE NEW.codcom END;
  -- El BEFORE trigger determina el estado usando las unidades reales y la factura.
  UPDATE public.compra SET estcom=estcom WHERE codcom=compra_id;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS hu002_estado_unidades ON public.unidad;
CREATE TRIGGER hu002_estado_unidades AFTER INSERT OR DELETE ON public.unidad FOR EACH ROW EXECUTE FUNCTION public.hu002_actualizar_estado();
DROP TRIGGER IF EXISTS hu002_estado_factura ON public.factura_compra;
CREATE TRIGGER hu002_estado_factura AFTER INSERT ON public.factura_compra FOR EACH ROW EXECUTE FUNCTION public.hu002_actualizar_estado();

CREATE OR REPLACE FUNCTION public.hu002_consultar_unidades(p_codcom bigint)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE compra public.compra%ROWTYPE; factura jsonb; unidades jsonb; identificadas bigint;
BEGIN
  IF coalesce(public.hu026_rol_actual(),'') NOT IN ('Gerente','Administradora') THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Perfil no autorizado';
  END IF;
  SELECT * INTO compra FROM public.compra WHERE codcom=p_codcom;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Compra inexistente'; END IF;
  SELECT jsonb_build_object('codfac',codfac::text,'emisor',emisor,'numero',numero,'fecha_emision',fecha_emision,
    'cantidad_motos',cantidad_motos,'archivo_adjuntado',false) INTO factura FROM public.factura_compra WHERE codcom=p_codcom;
  SELECT count(*),coalesce(jsonb_agg(public.hu002_proyeccion_unidad(u) ORDER BY coduni),'[]'::jsonb)
    INTO identificadas,unidades FROM public.unidad u WHERE codcom=p_codcom;
  RETURN jsonb_build_object('codcom',p_codcom::text,'cantidad_comprada',compra.cancom,
    'cantidad_identificada',identificadas,'cantidad_pendiente',greatest(compra.cancom-identificadas,0),
    'estcom',compra.estcom,'factura',factura,'unidades',unidades);
END $$;

CREATE OR REPLACE FUNCTION public.hu002_registrar_factura(p_codcom bigint,p_emisor text,p_numero text,p_fecha_emision date,p_cantidad_motos integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE compra public.compra%ROWTYPE; anterior public.factura_compra%ROWTYPE; resultado jsonb; autor bigint;
BEGIN
  IF coalesce(public.hu026_rol_actual(),'') NOT IN ('Gerente','Administradora') THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Perfil no autorizado';
  END IF;
  p_emisor := btrim(regexp_replace(p_emisor,'[[:space:]]+',' ','g'));
  p_numero := btrim(regexp_replace(p_numero,'[[:space:]]+',' ','g'));
  IF coalesce(p_emisor,'')='' OR char_length(p_emisor)>160 OR coalesce(p_numero,'')='' OR char_length(p_numero)>80
    OR p_fecha_emision IS NULL OR p_fecha_emision<'0001-01-01'::date OR p_fecha_emision>'9999-12-31'::date
    OR p_cantidad_motos IS NULL OR p_cantidad_motos<=0 THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Metadatos de factura inválidos';
  END IF;
  SELECT * INTO compra FROM public.compra WHERE codcom=p_codcom FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Compra inexistente'; END IF;
  SELECT * INTO anterior FROM public.factura_compra WHERE codcom=p_codcom;
  IF FOUND THEN
    IF anterior.emisor<>p_emisor OR anterior.numero<>p_numero OR anterior.fecha_emision<>p_fecha_emision OR anterior.cantidad_motos<>p_cantidad_motos THEN
      RAISE EXCEPTION USING ERRCODE='PT413', MESSAGE='Factura diferente; requiere revisión';
    END IF;
  ELSE
    SELECT codusu INTO autor FROM public.usuario WHERE uuidusu=auth.uid() AND estusu;
    INSERT INTO public.factura_compra(codcom,emisor,numero,fecha_emision,cantidad_motos,codusu)
    VALUES(p_codcom,p_emisor,p_numero,p_fecha_emision,p_cantidad_motos,autor);
  END IF;
  resultado := public.hu002_consultar_unidades(p_codcom);
  RETURN jsonb_build_object('codcom',p_codcom::text,'estcom',resultado->'estcom','factura',resultado->'factura',
    'requiere_revision',p_cantidad_motos<>compra.cancom);
END $$;

-- Retirar la firma anterior al reaplicar: no dejar una sobrecarga con cantidad enviada por el cliente.
DROP FUNCTION IF EXISTS public.hu002_identificar_unidades(bigint,integer,jsonb);
CREATE OR REPLACE FUNCTION public.hu002_identificar_unidades(p_codcom bigint,p_unidades jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE compra public.compra%ROWTYPE; factura public.factura_compra%ROWTYPE; elemento jsonb;
  llave bigint; motor text; chasis text; color text; modelo bigint; identificadas bigint;
BEGIN
  IF coalesce(public.hu026_rol_actual(),'') NOT IN ('Gerente','Administradora') THEN
    RAISE EXCEPTION USING ERRCODE='42501', MESSAGE='Perfil no autorizado';
  END IF;
  IF jsonb_typeof(p_unidades) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Se requiere un lote de unidades';
  END IF;
  IF jsonb_array_length(p_unidades)<1 OR jsonb_array_length(p_unidades)>100 THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Lote o cantidad inválidos';
  END IF;
  SELECT * INTO compra FROM public.compra WHERE codcom=p_codcom FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Compra inexistente'; END IF;
  SELECT * INTO factura FROM public.factura_compra WHERE codcom=p_codcom;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT410', MESSAGE='Registrar factura recibida'; END IF;
  IF factura.cantidad_motos<>compra.cancom THEN
    RAISE EXCEPTION USING ERRCODE='PT411', MESSAGE='Cantidad de factura discrepante';
  END IF;
  FOR elemento IN SELECT value FROM jsonb_array_elements(p_unidades) LOOP
    IF jsonb_typeof(elemento) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Unidad inválida'; END IF;
    IF EXISTS(SELECT 1 FROM jsonb_object_keys(elemento) AS k WHERE k NOT IN ('nummotuni','chauni','codmod','coluni'))
      OR jsonb_typeof(elemento->'nummotuni') IS DISTINCT FROM 'string'
      OR jsonb_typeof(elemento->'chauni') IS DISTINCT FROM 'string'
      OR jsonb_typeof(elemento->'coluni') IS DISTINCT FROM 'string'
      OR coalesce(elemento->>'codmod','') !~ '^[1-9][0-9]*$' THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Campos de unidad inválidos';
    END IF;
    motor:=public.hu002_normalizar(elemento->>'nummotuni'); chasis:=public.hu002_normalizar(elemento->>'chauni');
    color:=btrim(regexp_replace(elemento->>'coluni','[[:space:]]+',' ','g'));
    IF motor='' OR chasis='' OR color='' OR char_length(motor)>100 OR char_length(chasis)>100 OR char_length(color)>50
      OR length(elemento->>'codmod')>19 OR (elemento->>'codmod')::numeric>9223372036854775807 THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Datos de unidad fuera de rango';
    END IF;
    modelo:=(elemento->>'codmod')::bigint;
    IF modelo<>compra.codmod OR public.hu002_normalizar(color)<>public.hu002_normalizar(compra.colcom) THEN
      RAISE EXCEPTION USING ERRCODE='PT411', MESSAGE='Modelo o color discrepante';
    END IF;
  END LOOP;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(p_unidades) GROUP BY public.hu002_normalizar(value->>'nummotuni') HAVING count(*)>1)
    OR EXISTS(SELECT 1 FROM jsonb_array_elements(p_unidades) GROUP BY public.hu002_normalizar(value->>'chauni') HAVING count(*)>1) THEN
    RAISE EXCEPTION USING ERRCODE='PT409', MESSAGE='Series repetidas dentro del lote';
  END IF;
  -- Adquirir todas las series en orden para lotes de compras diferentes.
  FOR llave IN SELECT DISTINCT k FROM (
    SELECT pg_catalog.hashtextextended('motor:'||public.hu002_normalizar(value->>'nummotuni'),2) k FROM jsonb_array_elements(p_unidades)
    UNION ALL SELECT pg_catalog.hashtextextended('chasis:'||public.hu002_normalizar(value->>'chauni'),2) FROM jsonb_array_elements(p_unidades)
  ) claves ORDER BY k LOOP PERFORM pg_catalog.pg_advisory_xact_lock(llave); END LOOP;
  FOR elemento IN SELECT value FROM jsonb_array_elements(p_unidades) LOOP
    PERFORM public.hu002_comprobar_series(elemento->>'nummotuni',elemento->>'chauni');
  END LOOP;
  SELECT count(*) INTO identificadas FROM public.unidad WHERE codcom=p_codcom;
  IF identificadas+jsonb_array_length(p_unidades)>compra.cancom THEN
    RAISE EXCEPTION USING ERRCODE='PT412', MESSAGE='El lote excede las unidades pendientes';
  END IF;
  INSERT INTO public.unidad(codcom,codmod,nummotuni,chauni,coluni)
  SELECT p_codcom,(value->>'codmod')::bigint,public.hu002_normalizar(value->>'nummotuni'),
    public.hu002_normalizar(value->>'chauni'),btrim(regexp_replace(value->>'coluni','[[:space:]]+',' ','g'))
  FROM jsonb_array_elements(p_unidades);
  RETURN public.hu002_consultar_unidades(p_codcom);
END $$;

