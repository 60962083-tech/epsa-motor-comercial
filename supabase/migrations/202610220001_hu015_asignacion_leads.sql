  ON public.asignacionlead(codlea, fecale DESC, codale DESC);

CREATE OR REPLACE FUNCTION public.hu015_asignar_responsable_lead(
  p_codlea bigint,
  p_codusunuevo bigint,
  p_codusuesperado bigint DEFAULT NULL,
  p_motivo text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_autor bigint;
  v_rol text;
  v_actual bigint;
  v_motivo text;
  v_lead public.lead%ROWTYPE;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_autor, v_rol
  FROM public.usuario AS u
  JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu AND r.estrol
  FOR SHARE OF u, r;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado para asignar leads';
  END IF;

  IF p_codlea IS NULL OR p_codlea <= 0 OR p_codusunuevo IS NULL OR p_codusunuevo <= 0
    OR (p_codusuesperado IS NOT NULL AND p_codusuesperado <= 0) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Identificadores inválidos';
  END IF;

  SELECT l.* INTO v_lead
  FROM public.lead AS l
  WHERE l.codlea = p_codlea
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'Lead inexistente';
  END IF;
  v_actual := v_lead.codusu;

  IF NOT EXISTS (
    SELECT 1
    FROM public.usuario AS u
    JOIN public.rol AS r ON r.codrol = u.codrol
    WHERE u.codusu = p_codusunuevo
      AND u.estusu AND r.estrol
      AND r.nomrol IN ('Gerente', 'Administradora', 'Vendedor')
    FOR SHARE OF u, r
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT407', MESSAGE = 'Responsable inexistente o inactivo';
  END IF;

  v_motivo := NULLIF(pg_catalog.btrim(
    pg_catalog.regexp_replace(COALESCE(p_motivo, ''), '^[[:space:]]+|[[:space:]]+$', '', 'g')
  ), '');
  IF v_motivo IS NOT NULL AND pg_catalog.char_length(v_motivo) > 250 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El motivo admite hasta 250 caracteres';
  END IF;

  -- Reintentar la misma asignación es éxito sin una segunda fila de historial.
  IF v_actual IS NOT DISTINCT FROM p_codusunuevo THEN
    RETURN pg_catalog.jsonb_build_object(
      'codlea', p_codlea::text,
      'responsableAnterior', v_actual::text,
      'responsableActual', v_actual::text,
      'cambioRealizado', false
    );
  END IF;

  IF v_actual IS DISTINCT FROM p_codusuesperado THEN
    RAISE EXCEPTION USING ERRCODE = 'PT416', MESSAGE = 'El responsable actual cambió; vuelve a consultar el lead';
  END IF;

  IF v_actual IS NOT NULL AND v_motivo IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El motivo es obligatorio para transferir un lead';
  END IF;

  UPDATE public.lead SET codusu = p_codusunuevo WHERE codlea = p_codlea;
  INSERT INTO public.asignacionlead(codlea, codusuant, codusunue, codusuaut, fecale, motale)
  VALUES (p_codlea, v_actual, p_codusunuevo, v_autor, CURRENT_TIMESTAMP, v_motivo);

  RETURN pg_catalog.jsonb_build_object(
    'codlea', p_codlea::text,
    'responsableAnterior', v_actual::text,
    'responsableActual', p_codusunuevo::text,
    'cambioRealizado', true
  );
END;
$$;

REVOKE ALL ON FUNCTION public.hu015_asignar_responsable_lead(bigint,bigint,bigint,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.hu015_asignar_responsable_lead(bigint,bigint,bigint,text) TO authenticated;

-- La identidad y el rol determinan el alcance; no hay filtro de codusu aportado por el cliente.
CREATE OR REPLACE FUNCTION public.hu015_listar_leads(p_limite integer DEFAULT 50, p_offset integer DEFAULT 0)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_codusu bigint;
  v_rol text;
  v_resultado jsonb;
BEGIN
  SELECT u.codusu, r.nomrol INTO v_codusu, v_rol
  FROM public.usuario AS u
  JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu AND r.estrol
  FOR SHARE OF u, r;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado para consultar leads';
  END IF;
  IF p_limite IS NULL OR p_limite NOT BETWEEN 1 AND 100 OR p_offset IS NULL OR p_offset < 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Paginación inválida';
  END IF;

  SELECT COALESCE(pg_catalog.jsonb_agg(q.item ORDER BY q.fecreglea DESC, q.codlea DESC), '[]'::jsonb)
  INTO v_resultado
  FROM (
    SELECT l.codlea, l.fecreglea,
      pg_catalog.jsonb_build_object(
        'codlea', l.codlea::text,
        'nomlea', l.nomlea,
        'tellea', l.tellea,
        'codmod', l.codmod::text,
        'nommod', m.nommod,
        'collea', l.collea,
        'canlea', l.canlea,
        'orilea', l.orilea,
        'codcwa', l.codcwa::text,
        'receptorWhatsapp', cw.numcwa,
        'codsed', l.codsed::text,
        'nomsed', ubi.nomubi,
        'estlea', l.estlea,
        'obslea', l.obslea,
        'fecreglea', l.fecreglea,
        'codusu', l.codusu::text,
        'responsable', CASE WHEN u.codusu IS NULL THEN NULL ELSE pg_catalog.jsonb_build_object(
          'codusu', u.codusu::text,
          'nomusu', u.nomusu,
          'apepatusu', u.apepatusu,
          'apematusu', u.apematusu,
          'rol', r.nomrol
        ) END
      ) AS item
    FROM public.lead AS l
    LEFT JOIN public.modelo AS m ON m.codmod = l.codmod
    LEFT JOIN public.canalwhatsapp AS cw ON cw.codcwa = l.codcwa
    LEFT JOIN public.sede AS s ON s.codsed = l.codsed
    LEFT JOIN public.ubicacion AS ubi ON ubi.codubi = s.codubi
    LEFT JOIN public.usuario AS u ON u.codusu = l.codusu
    LEFT JOIN public.rol AS r ON r.codrol = u.codrol
    WHERE v_rol IN ('Gerente', 'Administradora') OR l.codusu = v_codusu
    ORDER BY l.fecreglea DESC, l.codlea DESC
    LIMIT p_limite OFFSET p_offset
  ) AS q;
  RETURN v_resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.hu015_listar_leads(integer,integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.hu015_listar_leads(integer,integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.hu015_listar_responsables()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_rol text;
  v_resultado jsonb;
BEGIN
  SELECT r.nomrol INTO v_rol
  FROM public.usuario AS u
  JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.uuidusu = auth.uid() AND u.estusu AND r.estrol
  FOR SHARE OF u, r;
  IF NOT FOUND OR v_rol NOT IN ('Gerente', 'Administradora') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado para consultar responsables';
  END IF;

  SELECT COALESCE(pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
    'codusu', u.codusu::text,
    'nomusu', u.nomusu,
    'apepatusu', u.apepatusu,
    'apematusu', u.apematusu,
    'rol', r.nomrol
  ) ORDER BY r.nomrol, u.apepatusu, u.apematusu, u.nomusu, u.codusu), '[]'::jsonb)
  INTO v_resultado
  FROM public.usuario AS u
  JOIN public.rol AS r ON r.codrol = u.codrol
  WHERE u.estusu AND r.estrol
    AND r.nomrol IN ('Gerente', 'Administradora', 'Vendedor');
  RETURN v_resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.hu015_listar_responsables() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.hu015_listar_responsables() TO authenticated;

