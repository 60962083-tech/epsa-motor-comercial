-- Historial append-only de asignaciones. lead.codusu sigue siendo el responsable actual.
CREATE TABLE IF NOT EXISTS public.asignacionlead (
  codale bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codlea bigint NOT NULL REFERENCES public.lead(codlea),
  codusuant bigint NULL REFERENCES public.usuario(codusu),
  codusunue bigint NOT NULL REFERENCES public.usuario(codusu),
  codusuaut bigint NOT NULL REFERENCES public.usuario(codusu),
  fecale timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  motale varchar(250) NULL,
  CONSTRAINT chk_hu015_asignacion_motivo CHECK (
    motale IS NULL OR (pg_catalog.btrim(motale) <> '' AND pg_catalog.char_length(motale) <= 250)
  )
);

ALTER TABLE public.asignacionlead ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.asignacionlead FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.asignacionlead_codale_seq FROM PUBLIC, anon, authenticated;
DROP POLICY IF EXISTS hu015_asignacionlead_solo_rpc ON public.asignacionlead;
CREATE POLICY hu015_asignacionlead_solo_rpc ON public.asignacionlead
  AS RESTRICTIVE FOR ALL TO PUBLIC USING (false) WITH CHECK (false);

-- Apoya la consulta de leads por responsable y la revisión cronológica por lead.
CREATE INDEX IF NOT EXISTS idx_hu015_lead_codusu ON public.lead(codusu);
