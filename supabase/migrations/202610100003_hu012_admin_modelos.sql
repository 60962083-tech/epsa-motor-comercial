CREATE OR REPLACE FUNCTION public.hu012_normalizar_colores(p_colores text[])
RETURNS text[]
LANGUAGE plpgsql IMMUTABLE SET search_path = ''
AS $$
DECLARE
  entrada text;
  limpio text;
  salida text[] := ARRAY[]::text[];
BEGIN
  IF p_colores IS NULL THEN RETURN salida; END IF;
  FOREACH entrada IN ARRAY p_colores LOOP
    IF entrada IS NULL THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Cada color debe ser texto';
    END IF;
    limpio := pg_catalog.btrim(pg_catalog.regexp_replace(entrada, '[[:space:]]+', ' ', 'g'));
    IF limpio = '' OR pg_catalog.char_length(limpio) > 50 THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Cada color debe tener entre 1 y 50 caracteres';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM pg_catalog.unnest(salida) AS existentes(nombre)
      WHERE pg_catalog.lower(existentes.nombre) = pg_catalog.lower(limpio)
    ) THEN
      salida := pg_catalog.array_append(salida, limpio);
    END IF;
  END LOOP;
  RETURN salida;
END
$$;

CREATE OR REPLACE FUNCTION public.hu012_guardar_colores(p_codmod bigint, p_colores text[])
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  color text;
BEGIN
  UPDATE public.colormodelo SET estcmo = false
  WHERE codmod = p_codmod AND estcmo = true;

  FOREACH color IN ARRAY public.hu012_normalizar_colores(p_colores) LOOP
    UPDATE public.colormodelo
      SET nomcmo = color, estcmo = true
      WHERE codmod = p_codmod
        AND pg_catalog.lower(pg_catalog.btrim(pg_catalog.regexp_replace(nomcmo, '[[:space:]]+', ' ', 'g')))
          = pg_catalog.lower(color);
    IF NOT FOUND THEN
      INSERT INTO public.colormodelo(codmod, nomcmo, estcmo)
      VALUES (p_codmod, color, true);
    END IF;
  END LOOP;
END
$$;

