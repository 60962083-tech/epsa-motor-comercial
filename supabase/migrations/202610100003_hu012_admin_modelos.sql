CREATE OR REPLACE FUNCTION public.hu012_validar_url_imagen(p_urlimo text)
RETURNS text
LANGUAGE plpgsql IMMUTABLE SET search_path = ''
AS $$
DECLARE
  url_limpia text := pg_catalog.btrim(p_urlimo);
  host text;
BEGIN
  IF p_urlimo IS NULL OR url_limpia = '' OR pg_catalog.char_length(url_limpia) > 2048
    OR url_limpia ~ '[[:space:][:cntrl:]]' THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Referencia de imagen inválida';
  END IF;

  IF pg_catalog.left(url_limpia, 8) = '/images/' THEN
    IF pg_catalog.length(url_limpia) <= 8
      OR pg_catalog.strpos(url_limpia, E'\\') > 0
      OR pg_catalog.strpos(url_limpia, '?') > 0
      OR pg_catalog.strpos(url_limpia, '#') > 0
      OR url_limpia ~* '%(2e|2f|5c)'
      OR EXISTS (
        SELECT 1 FROM pg_catalog.unnest(pg_catalog.string_to_array(pg_catalog.substr(url_limpia, 9), '/')) AS partes(segmento)
        WHERE partes.segmento IN ('', '.', '..')
      ) THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Referencia de imagen inválida';
    END IF;
    RETURN url_limpia;
  END IF;

  IF pg_catalog.left(url_limpia, 8) = 'https://' THEN
    host := (pg_catalog.regexp_match(url_limpia, '^https://([^/?#]+)'))[1];
    IF host IS NOT NULL AND host <> '' AND pg_catalog.strpos(host, '@') = 0 THEN
      RETURN url_limpia;
    END IF;
  END IF;

  RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Referencia de imagen inválida';
END
$$;

CREATE OR REPLACE FUNCTION public.hu012_validar_publicacion_modelo(p_codmod bigint)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  modelo_actual public.modelo%ROWTYPE;
BEGIN
  SELECT * INTO modelo_actual FROM public.modelo WHERE codmod = p_codmod;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Modelo inexistente';
  END IF;

  IF modelo_actual.codtmo IS NULL OR NOT EXISTS (
      SELECT 1 FROM public.tipomotocar t WHERE t.codtmo = modelo_actual.codtmo
    )
    OR pg_catalog.btrim(modelo_actual.nommod) = ''
    OR pg_catalog.btrim(modelo_actual.marmod) = ''
    OR pg_catalog.btrim(modelo_actual.desmod) = ''
    OR pg_catalog.btrim(modelo_actual.carmod) = ''
    OR NOT EXISTS (
      SELECT 1 FROM public.imagenmodelo i
      WHERE i.codmod = p_codmod AND i.estimo = true AND pg_catalog.btrim(i.urlimo) <> ''
    ) THEN
    RAISE EXCEPTION USING ERRCODE='PT422', MESSAGE='Modelo incompleto para publicación';
  END IF;
END
$$;

