CREATE OR REPLACE FUNCTION public.hu012_actualizar_modelo(p_codmod bigint, p_cambios jsonb)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  actual public.modelo%ROWTYPE;
  nuevo_codtmo bigint;
  nuevo_nombre text;
  nueva_marca text;
  nueva_descripcion text;
  nuevas_caracteristicas text;
  nuevo_precio numeric;
  colores text[];
  campo text;
BEGIN
  PERFORM public.hu012_exigir_gestion_modelos();
  IF p_cambios IS NULL OR pg_catalog.jsonb_typeof(p_cambios) IS DISTINCT FROM 'object' OR p_cambios = '{}'::jsonb THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Debe indicar al menos un campo para actualizar';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_catalog.jsonb_object_keys(p_cambios) AS campos(nombre)
    WHERE campos.nombre NOT IN ('codtmo', 'nommod', 'marmod', 'desmod', 'carmod', 'premod', 'colores')
  ) THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Campo de modelo no permitido';
  END IF;
  SELECT * INTO actual FROM public.modelo WHERE codmod = p_codmod FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404', MESSAGE='Modelo inexistente'; END IF;

  nuevo_codtmo := actual.codtmo;
  nuevo_nombre := actual.nommod;
  nueva_marca := actual.marmod;
  nueva_descripcion := actual.desmod;
  nuevas_caracteristicas := actual.carmod;
  nuevo_precio := actual.premod;

  IF p_cambios ? 'codtmo' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'codtmo') NOT IN ('string', 'number')
      OR (p_cambios->>'codtmo') !~ '^[1-9][0-9]*$' THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='codtmo inválido';
    END IF;
    nuevo_codtmo := (p_cambios->>'codtmo')::bigint;
  END IF;
  IF p_cambios ? 'nommod' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'nommod') <> 'string' THEN RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='nommod inválido'; END IF;
    nuevo_nombre := pg_catalog.regexp_replace(pg_catalog.btrim(p_cambios->>'nommod'), '[[:space:]]+', ' ', 'g');
  END IF;
  IF p_cambios ? 'marmod' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'marmod') <> 'string' THEN RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='marmod inválido'; END IF;
    nueva_marca := pg_catalog.regexp_replace(pg_catalog.btrim(p_cambios->>'marmod'), '[[:space:]]+', ' ', 'g');
  END IF;
  IF p_cambios ? 'desmod' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'desmod') <> 'string' THEN RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='desmod inválido'; END IF;
    nueva_descripcion := pg_catalog.btrim(p_cambios->>'desmod');
  END IF;
  IF p_cambios ? 'carmod' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'carmod') <> 'string' THEN RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='carmod inválido'; END IF;
    nuevas_caracteristicas := pg_catalog.btrim(p_cambios->>'carmod');
  END IF;
  IF p_cambios ? 'premod' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'premod') = 'null' THEN
      nuevo_precio := NULL;
    ELSIF pg_catalog.jsonb_typeof(p_cambios->'premod') = 'number' THEN
      nuevo_precio := (p_cambios->>'premod')::numeric;
    ELSE
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='premod inválido';
    END IF;
  END IF;

  IF nuevo_codtmo <= 0 OR nuevo_nombre IS NULL OR nuevo_nombre = '' OR pg_catalog.char_length(nuevo_nombre) > 100
    OR nueva_marca IS NULL OR nueva_marca = '' OR pg_catalog.char_length(nueva_marca) > 100
    OR nueva_descripcion IS NULL OR nueva_descripcion = '' OR nuevas_caracteristicas IS NULL OR nuevas_caracteristicas = ''
    OR (nuevo_precio IS NOT NULL AND (nuevo_precio < 0 OR nuevo_precio > 99999999.99 OR pg_catalog.scale(nuevo_precio) > 2)) THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Datos de modelo inválidos';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.tipomotocar t WHERE t.codtmo = nuevo_codtmo FOR SHARE) THEN
    RAISE EXCEPTION USING ERRCODE='PT405', MESSAGE='Tipo de motocar inexistente';
  END IF;

  UPDATE public.modelo SET codtmo = nuevo_codtmo, nommod = nuevo_nombre, marmod = nueva_marca,
    desmod = nueva_descripcion, carmod = nuevas_caracteristicas, premod = nuevo_precio
  WHERE codmod = p_codmod;

  IF p_cambios ? 'colores' THEN
    IF pg_catalog.jsonb_typeof(p_cambios->'colores') <> 'array' THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='colores debe ser un arreglo';
    END IF;
    IF EXISTS (
      SELECT 1 FROM pg_catalog.jsonb_array_elements(p_cambios->'colores') AS elementos(valor)
      WHERE pg_catalog.jsonb_typeof(elementos.valor) <> 'string'
    ) THEN
      RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Cada color debe ser texto';
    END IF;
    SELECT COALESCE(pg_catalog.array_agg(elementos.valor #>> '{}'), ARRAY[]::text[])
      INTO colores FROM pg_catalog.jsonb_array_elements(p_cambios->'colores') AS elementos(valor);
    PERFORM public.hu012_guardar_colores(p_codmod, colores);
  END IF;
  IF actual.estmod = 'Publicado' THEN
    PERFORM public.hu012_validar_publicacion_modelo(p_codmod);
  END IF;
  RETURN public.hu012_modelo_admin_json(p_codmod);
END
$$;

