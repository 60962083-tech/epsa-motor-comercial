CREATE OR REPLACE FUNCTION public.hu012_crear_modelo(
  p_codtmo bigint,
  p_nommod text,
  p_marmod text,
  p_desmod text,
  p_carmod text,
  p_premod numeric,
  p_colores text[],
  p_estmod text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  creado public.modelo%ROWTYPE;
  nombre text;
  marca text;
  descripcion text;
  caracteristicas text;
BEGIN
  PERFORM public.hu012_exigir_gestion_modelos();
  nombre := pg_catalog.regexp_replace(pg_catalog.btrim(p_nommod), '[[:space:]]+', ' ', 'g');
  marca := pg_catalog.regexp_replace(pg_catalog.btrim(p_marmod), '[[:space:]]+', ' ', 'g');
  descripcion := pg_catalog.btrim(p_desmod);
  caracteristicas := pg_catalog.btrim(p_carmod);

  IF p_codtmo IS NULL OR p_codtmo <= 0 OR nombre IS NULL OR nombre = '' OR pg_catalog.char_length(nombre) > 100
    OR marca IS NULL OR marca = '' OR pg_catalog.char_length(marca) > 100
    OR descripcion IS NULL OR descripcion = '' OR caracteristicas IS NULL OR caracteristicas = ''
    OR p_estmod IS NULL OR p_estmod NOT IN ('Borrador', 'Publicado', 'No publicado')
    OR (p_premod IS NOT NULL AND (p_premod < 0 OR p_premod > 99999999.99 OR pg_catalog.scale(p_premod) > 2)) THEN
    RAISE EXCEPTION USING ERRCODE='PT400', MESSAGE='Datos de modelo inválidos';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.tipomotocar t WHERE t.codtmo = p_codtmo FOR SHARE) THEN
    RAISE EXCEPTION USING ERRCODE='PT405', MESSAGE='Tipo de motocar inexistente';
  END IF;

  INSERT INTO public.modelo(codtmo, nommod, marmod, desmod, carmod, premod, estmod)
  VALUES (p_codtmo, nombre, marca, descripcion, caracteristicas, p_premod, p_estmod)
  RETURNING * INTO creado;

  PERFORM public.hu012_guardar_colores(creado.codmod, p_colores);
  IF creado.estmod = 'Publicado' THEN
    PERFORM public.hu012_validar_publicacion_modelo(creado.codmod);
  END IF;
  RETURN public.hu012_modelo_admin_json(creado.codmod);
END
$$;

