CREATE TRIGGER hu033_reiniciar_techo_por_configuracion
AFTER UPDATE OF codtte, codpro, dettecuni ON public.unidad
FOR EACH ROW EXECUTE FUNCTION public.hu033_reiniciar_techo_por_configuracion();

