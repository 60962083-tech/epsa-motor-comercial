CREATE OR REPLACE FUNCTION public.hu033_proyectar_preparacion_unidad(p_coduni bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE resultado jsonb;
  condiciones text[];
BEGIN
  IF p_coduni IS NULL OR p_coduni <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'ID de unidad inválido';
  END IF;

  SELECT array_remove(ARRAY[
      CASE WHEN p.estarmado <> 'Terminado' THEN 'Armado pendiente' END,
      CASE WHEN u.codtte IS NULL THEN 'Configuración de techo pendiente' END,
      CASE WHEN u.codtte IS NOT NULL AND t.reqinsttte AND p.esttecho <> 'Instalado'
        THEN 'Instalación de techo pendiente' END,
      CASE WHEN u.codtte IS NOT NULL AND NOT t.reqinsttte AND p.esttecho <> 'No requiere'
        THEN 'Estado de techo incompatible con la configuración' END
    ]::text[], NULL::text)
  INTO condiciones
  FROM public.unidad u
  JOIN public.preparacionunidad p ON p.coduni = u.coduni
  LEFT JOIN public.tipotecho t ON t.codtte = u.codtte
  WHERE u.coduni = p_coduni;

  IF NOT FOUND THEN
    IF EXISTS (SELECT 1 FROM public.unidad WHERE coduni = p_coduni) THEN
      RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'La preparación de la unidad no está inicializada';
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'Unidad inexistente';
  END IF;

  SELECT pg_catalog.jsonb_build_object(
    'coduni', u.coduni::text,
    'armado', p.estarmado,
    'techo', pg_catalog.jsonb_build_object(
      'estado', p.esttecho,
      'codtte', t.codtte::text,
      'configuracion', t.nomtte,
      'requiereInstalacion', t.reqinsttte
    ),
    'version', p.versionprep::text,
    'preparacionCompleta', pg_catalog.cardinality(condiciones) = 0,
    'condicionesFaltantes', pg_catalog.to_jsonb(condiciones),
    'ultimaActualizacion', p.fecactualizacion,
    'actualizadoPor', CASE WHEN autor.codusu IS NULL THEN NULL ELSE
      pg_catalog.jsonb_build_object(
        'codusu', autor.codusu::text,
        'nombre', pg_catalog.btrim(pg_catalog.concat_ws(' ', autor.nomusu, autor.apepatusu, autor.apematusu))
      ) END
  ) INTO resultado
  FROM public.unidad u
  JOIN public.preparacionunidad p ON p.coduni = u.coduni
  LEFT JOIN public.tipotecho t ON t.codtte = u.codtte
  LEFT JOIN public.usuario autor ON autor.codusu = p.codusuactualiza
  WHERE u.coduni = p_coduni;

  RETURN resultado;
END
$$;

CREATE OR REPLACE FUNCTION public.hu033_consultar_preparacion_unidad(p_coduni bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE resultado jsonb;
BEGIN
  IF coalesce(public.hu026_rol_actual(), '') NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado';
  END IF;
  IF p_coduni IS NULL OR p_coduni <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'ID de unidad inválido';
  END IF;

  resultado := public.hu033_proyectar_preparacion_unidad(p_coduni);
  RETURN pg_catalog.jsonb_build_object(
    'actual', resultado,
    'historial', coalesce((
      SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
        'codhprep', h.codhprep::text,
        'etapa', h.etapaprep,
        'estadoAnterior', h.estadoanterior,
        'estadoNuevo', h.estadonuevo,
        'fecha', h.fecprep,
        'observacion', h.obspreparacion,
        'fuente', h.fuente,
        'proveedor', CASE WHEN p.codpro IS NULL THEN NULL ELSE
          pg_catalog.jsonb_build_object('codpro', p.codpro::text, 'nombre', p.nompro) END,
        'autor', pg_catalog.jsonb_build_object(
          'codusu', u.codusu::text,
          'nombre', pg_catalog.btrim(pg_catalog.concat_ws(' ', u.nomusu, u.apepatusu, u.apematusu))
        )
      ) ORDER BY h.fecprep, h.codhprep)
      FROM public.historialpreparacionunidad h
      JOIN public.usuario u ON u.codusu = h.codusu
      LEFT JOIN public.proveedor p ON p.codpro = h.codpro
      WHERE h.coduni = p_coduni
    ), '[]'::jsonb)
  );
END
$$;

CREATE OR REPLACE FUNCTION public.hu033_actualizar_preparacion_unidad(
  p_coduni bigint,
  p_etapa text,
  p_estado text,
  p_version_esperada bigint,
  p_observacion text,
  p_fuente text,
  p_idempotencia text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE actor bigint;
  rol_actual text;
  unidad_actual public.unidad%ROWTYPE;
  preparacion_actual public.preparacionunidad%ROWTYPE;
  evento_existente public.historialpreparacionunidad%ROWTYPE;
  estado_actual text;
  observacion_normalizada text;
  clave_normalizada text;
  proveedor_evento bigint;
BEGIN
  rol_actual := public.hu026_rol_actual();
  IF coalesce(rol_actual, '') NOT IN ('Gerente', 'Administradora') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado';
  END IF;

  SELECT u.codusu INTO actor
  FROM public.usuario u
  WHERE u.uuidusu = auth.uid() AND u.estusu;
  IF actor IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado';
  END IF;

  IF p_coduni IS NULL OR p_coduni <= 0
     OR p_version_esperada IS NULL OR p_version_esperada < 1
     OR p_etapa IS NULL OR p_estado IS NULL
     OR p_etapa NOT IN ('Armado', 'Techo')
     OR p_fuente IS NULL OR p_fuente NOT IN ('Interno', 'Aviso proveedor') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Datos de preparación inválidos';
  END IF;
  IF (p_etapa = 'Armado' AND p_estado NOT IN ('Pendiente', 'Terminado'))
     OR (p_etapa = 'Techo' AND p_estado NOT IN ('Pendiente', 'En proceso', 'Instalado', 'No requiere')) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Estado inválido para la etapa indicada';
  END IF;

  clave_normalizada := nullif(btrim(p_idempotencia), '');
  IF clave_normalizada IS NULL OR char_length(clave_normalizada) > 128 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Clave de idempotencia inválida';
  END IF;
  observacion_normalizada := nullif(btrim(regexp_replace(coalesce(p_observacion, ''), '[[:space:]]+', ' ', 'g')), '');
  IF char_length(observacion_normalizada) > 500 THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'La observación excede el límite permitido';
  END IF;

  -- Serialize retries with the same actor/key before checking the event ledger.
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(
    'hu033-idempotencia:' || actor::text || ':' || clave_normalizada, 33033));
  SELECT * INTO evento_existente
  FROM public.historialpreparacionunidad h
  WHERE h.codusu = actor AND h.idempotencia = clave_normalizada;
  IF FOUND THEN
    IF evento_existente.coduni IS DISTINCT FROM p_coduni
       OR evento_existente.etapaprep IS DISTINCT FROM p_etapa
       OR evento_existente.estadonuevo IS DISTINCT FROM p_estado
       OR evento_existente.versionesperada IS DISTINCT FROM p_version_esperada
       OR evento_existente.obspreparacion IS DISTINCT FROM observacion_normalizada
       OR evento_existente.fuente IS DISTINCT FROM p_fuente THEN
      RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'La clave de idempotencia ya fue usada con otra operación';
    END IF;
    RETURN public.hu033_proyectar_preparacion_unidad(p_coduni);
  END IF;

  SELECT * INTO unidad_actual
  FROM public.unidad u
  WHERE u.coduni = p_coduni
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'Unidad inexistente';
  END IF;

  SELECT * INTO preparacion_actual
  FROM public.preparacionunidad p
  WHERE p.coduni = p_coduni
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'La preparación de la unidad no está inicializada';
  END IF;
  IF preparacion_actual.versionprep <> p_version_esperada THEN
    RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'La preparación cambió; vuelve a cargar el estado actual';
  END IF;

  IF p_etapa = 'Armado' THEN
    estado_actual := preparacion_actual.estarmado;
  ELSE
    estado_actual := preparacion_actual.esttecho;
    IF unidad_actual.codtte IS NULL THEN
      RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'Define primero la configuración del techo';
    END IF;
    IF p_estado = 'No requiere' AND EXISTS (
      SELECT 1 FROM public.tipotecho t WHERE t.codtte = unidad_actual.codtte AND t.reqinsttte
    ) THEN
      RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'La configuración actual requiere instalación de techo';
    END IF;
    IF p_estado <> 'No requiere' AND EXISTS (
      SELECT 1 FROM public.tipotecho t WHERE t.codtte = unidad_actual.codtte AND NOT t.reqinsttte
    ) THEN
      RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'La configuración actual no requiere instalación de techo';
    END IF;
  END IF;

  IF p_fuente = 'Aviso proveedor'
     AND (p_etapa <> 'Techo' OR p_estado <> 'Instalado' OR unidad_actual.codpro IS NULL) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El aviso de proveedor requiere registrar un techo instalado con proveedor configurado';
  END IF;

  IF p_estado = estado_actual THEN
    RETURN public.hu033_proyectar_preparacion_unidad(p_coduni);
  END IF;

  IF ((p_etapa = 'Armado' AND estado_actual = 'Terminado' AND p_estado = 'Pendiente')
      OR (p_etapa = 'Techo' AND (
        (estado_actual = 'Instalado' AND p_estado IN ('Pendiente', 'En proceso'))
        OR (estado_actual = 'En proceso' AND p_estado = 'Pendiente')
      ))) AND observacion_normalizada IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El retroceso requiere una observación';
  END IF;

  UPDATE public.preparacionunidad
  SET estarmado = CASE WHEN p_etapa = 'Armado' THEN p_estado ELSE estarmado END,
      esttecho = CASE WHEN p_etapa = 'Techo' THEN p_estado ELSE esttecho END,
      versionprep = versionprep + 1,
      fecactualizacion = now(),
      codusuactualiza = actor
  WHERE coduni = p_coduni;

  proveedor_evento := CASE WHEN p_fuente = 'Aviso proveedor' THEN unidad_actual.codpro ELSE NULL END;
  INSERT INTO public.historialpreparacionunidad(
    coduni, etapaprep, estadoanterior, estadonuevo, versionesperada,
    codusu, fecprep, obspreparacion, fuente, codpro, idempotencia
  ) VALUES (
    p_coduni, p_etapa, estado_actual, p_estado, p_version_esperada,
    actor, now(), observacion_normalizada, p_fuente, proveedor_evento, clave_normalizada
  );

  RETURN public.hu033_proyectar_preparacion_unidad(p_coduni);
END
$$;

CREATE OR REPLACE FUNCTION public.hu033_reiniciar_techo_por_configuracion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE actor bigint;
  rol_actual text;
  requiere_instalacion boolean;
  estado_nuevo text;
  preparacion_actual public.preparacionunidad%ROWTYPE;
BEGIN
  IF OLD.codtte IS NOT DISTINCT FROM NEW.codtte
     AND OLD.codpro IS NOT DISTINCT FROM NEW.codpro
     AND OLD.dettecuni IS NOT DISTINCT FROM NEW.dettecuni THEN
    RETURN NEW;
  END IF;

  rol_actual := public.hu026_rol_actual();
  IF coalesce(rol_actual, '') NOT IN ('Gerente', 'Administradora') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado';
  END IF;
  SELECT u.codusu INTO actor
  FROM public.usuario u
  WHERE u.uuidusu = auth.uid() AND u.estusu;
  IF actor IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no autorizado';
  END IF;

  IF NEW.codtte IS NULL THEN
    requiere_instalacion := NULL;
    estado_nuevo := 'Pendiente';
  ELSE
    SELECT t.reqinsttte INTO requiere_instalacion
    FROM public.tipotecho t
    WHERE t.codtte = NEW.codtte;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'Tipo de techo no disponible para recalcular la preparación';
    END IF;
    estado_nuevo := CASE WHEN requiere_instalacion THEN 'Pendiente' ELSE 'No requiere' END;
  END IF;

  SELECT * INTO preparacion_actual
  FROM public.preparacionunidad p
  WHERE p.coduni = NEW.coduni
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'La preparación de la unidad no está inicializada';
  END IF;

  UPDATE public.preparacionunidad
  SET esttecho = estado_nuevo,
      versionprep = versionprep + 1,
      fecactualizacion = now(),
      codusuactualiza = actor
  WHERE coduni = NEW.coduni;

  IF preparacion_actual.esttecho IS DISTINCT FROM estado_nuevo THEN
    INSERT INTO public.historialpreparacionunidad(
      coduni, etapaprep, estadoanterior, estadonuevo, versionesperada,
      codusu, fecprep, obspreparacion, fuente, codpro, idempotencia
    ) VALUES (
      NEW.coduni, 'Techo', preparacion_actual.esttecho, estado_nuevo, NULL,
      actor, now(), 'Avance de techo reajustado por cambio de configuración.',
      'Configuración techo', NEW.codpro, NULL
    );
  END IF;

  RETURN NEW;
END
$$;

