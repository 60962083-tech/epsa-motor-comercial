CREATE OR REPLACE FUNCTION public.hu033_inicializar_preparacion_unidad()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE estado_techo text;
BEGIN
  IF NEW.codtte IS NULL THEN
    estado_techo := 'Pendiente';
  ELSE
    SELECT CASE WHEN t.reqinsttte THEN 'Pendiente' ELSE 'No requiere' END
      INTO estado_techo
    FROM public.tipotecho t
    WHERE t.codtte = NEW.codtte;
    IF estado_techo IS NULL THEN
      RAISE EXCEPTION USING ERRCODE = 'PT409', MESSAGE = 'No se pudo determinar el estado inicial del techo';
    END IF;
  END IF;

  INSERT INTO public.preparacionunidad(coduni, estarmado, esttecho, versionprep, fecactualizacion)
  VALUES (NEW.coduni, 'Pendiente', estado_techo, 1, now())
  ON CONFLICT (coduni) DO NOTHING;
  RETURN NEW;
END
$$;

