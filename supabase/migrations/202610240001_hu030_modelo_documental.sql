DO $seguridad$
DECLARE
  v_tabla text;
  v_columna text;
  v_secuencia regclass;
BEGIN
  FOREACH v_tabla IN ARRAY ARRAY[
    'ubicacionclave','equivalenciaproducto','documentocompra','lineadocumentocompra',
    'vehiculodocumento','documentocompracompra','referenciacompra','intentodocumento'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', v_tabla);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated', v_tabla);
    EXECUTE format('DROP POLICY IF EXISTS hu030_denegar_acceso_directo ON public.%I', v_tabla);
    EXECUTE format('CREATE POLICY hu030_denegar_acceso_directo ON public.%I AS RESTRICTIVE FOR ALL TO PUBLIC USING (false) WITH CHECK (false)', v_tabla);
  END LOOP;

  FOR v_tabla, v_columna IN
    SELECT * FROM (VALUES
      ('ubicacionclave','coducl'), ('equivalenciaproducto','codequ'), ('documentocompra','coddoc'),
      ('lineadocumentocompra','codlin'), ('vehiculodocumento','codvehdoc'),
      ('documentocompracompra','coddcc'), ('referenciacompra','codref'), ('intentodocumento','codint')
    ) AS t(tabla, columna)
  LOOP
    v_secuencia := pg_get_serial_sequence('public.' || v_tabla, v_columna)::regclass;
    IF v_secuencia IS NOT NULL THEN
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', v_secuencia);
    END IF;
  END LOOP;
END
$seguridad$;

