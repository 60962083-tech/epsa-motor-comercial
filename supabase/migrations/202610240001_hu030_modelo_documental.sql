-- EMT-35 / HU-030 FASE 1: maestro documental y homologaciones aprobadas.
-- No crea compras, unidades, facturas HU-002 ni modifica proveedores operativos de unidad.

ALTER TABLE public.proveedor ADD COLUMN rucpro varchar(11);
ALTER TABLE public.proveedor ADD CONSTRAINT chk_proveedor_rucpro_formato
  CHECK (rucpro IS NULL OR rucpro ~ '^[0-9]{11}$');
CREATE UNIQUE INDEX uq_proveedor_rucpro ON public.proveedor(rucpro) WHERE rucpro IS NOT NULL;

DO $proveedor$
DECLARE
  v_id_ruc bigint;
  v_id_nombre bigint;
  v_cantidad integer;
  v_ruc_nombre varchar(11);
  v_nombre_ruc text;
BEGIN
  SELECT codpro, nompro INTO v_id_ruc, v_nombre_ruc
  FROM public.proveedor WHERE rucpro = '20502913752';

  IF v_id_ruc IS NOT NULL
     AND public.hu026_nombre_normalizado(v_nombre_ruc) <> public.hu026_nombre_normalizado('CROSLAND AUTOMOTRIZ S.A.C.') THEN
    RAISE EXCEPTION 'El RUC 20502913752 ya pertenece a otro proveedor: %', v_nombre_ruc;
  END IF;

  SELECT count(*)::integer, min(codpro) INTO v_cantidad, v_id_nombre
  FROM public.proveedor
  WHERE public.hu026_nombre_normalizado(nompro) = public.hu026_nombre_normalizado('CROSLAND AUTOMOTRIZ S.A.C.');

  IF v_cantidad > 1 THEN
    RAISE EXCEPTION 'Hay más de un proveedor con nombre normalizado CROSLAND AUTOMOTRIZ S.A.C.';
  END IF;

  IF v_id_ruc IS NOT NULL THEN
    IF v_id_nombre IS NOT NULL AND v_id_nombre <> v_id_ruc THEN
      RAISE EXCEPTION 'El nombre de Crosland y el RUC 20502913752 pertenecen a proveedores distintos';
    END IF;
    RETURN;
  END IF;

  IF v_id_nombre IS NOT NULL THEN
    SELECT rucpro INTO v_ruc_nombre FROM public.proveedor WHERE codpro = v_id_nombre FOR UPDATE;
    IF v_ruc_nombre IS NOT NULL AND v_ruc_nombre <> '20502913752' THEN
      RAISE EXCEPTION 'CROSLAND AUTOMOTRIZ S.A.C. ya tiene otro RUC: %', v_ruc_nombre;
    END IF;
    UPDATE public.proveedor SET rucpro = '20502913752' WHERE codpro = v_id_nombre;
    RETURN;
  END IF;

  INSERT INTO public.proveedor(nompro, rucpro, estpro)
  VALUES ('CROSLAND AUTOMOTRIZ S.A.C.', '20502913752', true);
END
$proveedor$;

CREATE TABLE public.ubicacionclave (
  coducl bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claubi varchar(80) NOT NULL UNIQUE,
  codubi bigint NOT NULL UNIQUE REFERENCES public.ubicacion(codubi),
  estucl boolean NOT NULL DEFAULT true
);

DO $ubicacion$
DECLARE
  v_codubi bigint;
  v_codclave bigint;
  v_nombre text;
  v_tipo text;
  v_activa boolean;
  v_clave_activa boolean;
  v_cantidad integer;
BEGIN
  SELECT k.coducl, k.codubi, k.estucl INTO v_codclave, v_codubi, v_clave_activa
  FROM public.ubicacionclave k WHERE k.claubi = 'ALMACEN_CROSLAND_ANCON';

  IF v_codclave IS NOT NULL THEN
    IF v_clave_activa IS DISTINCT FROM true THEN
      RAISE EXCEPTION 'La clave ALMACEN_CROSLAND_ANCON existe pero está inactiva';
    END IF;
    SELECT nomubi, tipubi, estubi INTO v_nombre, v_tipo, v_activa
    FROM public.ubicacion WHERE codubi = v_codubi;
    IF public.hu026_nombre_normalizado(v_nombre) <> public.hu026_nombre_normalizado('Crossland Ancón')
       OR v_tipo <> 'Almacen' OR v_activa IS DISTINCT FROM true THEN
      RAISE EXCEPTION 'La clave ALMACEN_CROSLAND_ANCON apunta a una ubicación incompatible o inactiva';
    END IF;
    RETURN;
  END IF;

  SELECT count(*)::integer, min(codubi) INTO v_cantidad, v_codubi
  FROM public.ubicacion
  WHERE public.hu026_nombre_normalizado(nomubi) = public.hu026_nombre_normalizado('Crossland Ancón');

  IF v_cantidad = 0 THEN
    -- HU-026 normalmente crea esta ubicación; este alta idempotente cubre instalaciones incompletas.
    INSERT INTO public.ubicacion(nomubi, tipubi, estubi)
    VALUES ('Crossland Ancón', 'Almacen', true)
    RETURNING codubi INTO v_codubi;
  ELSIF v_cantidad <> 1 THEN
    RAISE EXCEPTION 'La ubicación Crossland Ancón no es inequívoca';
  END IF;

  SELECT nomubi, tipubi, estubi INTO v_nombre, v_tipo, v_activa
  FROM public.ubicacion WHERE codubi = v_codubi FOR SHARE;
  IF v_tipo <> 'Almacen' THEN
    RAISE EXCEPTION 'Crossland Ancón existe pero su tipo es %, se esperaba Almacen', v_tipo;
  END IF;
  IF v_activa IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'Crossland Ancón existe pero está inactiva';
  END IF;

  INSERT INTO public.ubicacionclave(claubi, codubi, estucl)
  VALUES ('ALMACEN_CROSLAND_ANCON', v_codubi, true);
END
$ubicacion$;

CREATE TABLE public.equivalenciaproducto (
  codequ bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codpro bigint NOT NULL REFERENCES public.proveedor(codpro),
  codext varchar(120) NOT NULL CHECK (btrim(codext) <> ''),
  claequ varchar(20) NOT NULL CHECK (claequ IN ('Vehiculo', 'Accesorio')),
  codmod bigint NULL REFERENCES public.modelo(codmod),
  estequ boolean NOT NULL DEFAULT true,
  fecaprequ timestamptz NOT NULL DEFAULT now(),
  codusuapr bigint NULL REFERENCES public.usuario(codusu),
  fueaprequ varchar(150),
  obsequ text,
  CONSTRAINT chk_equivalencia_modelo_por_clasificacion CHECK (
    (claequ = 'Vehiculo' AND codmod IS NOT NULL)
    OR (claequ = 'Accesorio' AND codmod IS NULL)
  )
);
CREATE UNIQUE INDEX uq_equivalenciaproducto_activa
  ON public.equivalenciaproducto(codpro, upper(btrim(codext))) WHERE estequ;

DO $semillas$
DECLARE
  v_proveedor bigint;
  v_modelo bigint;
  v_cantidad integer;
  v_existente record;
  v_codext text;
  v_claequ text;
  v_codmod bigint;
BEGIN
  SELECT codpro INTO v_proveedor FROM public.proveedor WHERE rucpro = '20502913752';
  IF v_proveedor IS NULL THEN RAISE EXCEPTION 'No se pudo resolver el proveedor Crosland por RUC'; END IF;

  SELECT count(*)::integer, min(codmod) INTO v_cantidad, v_modelo
  FROM public.modelo
  WHERE public.hu026_nombre_normalizado(nommod) = public.hu026_nombre_normalizado('Torito 250 4V GLP');
  IF v_cantidad <> 1 THEN
    RAISE EXCEPTION 'Se esperaba exactamente un modelo Torito 250 4V GLP y se encontraron %', v_cantidad;
  END IF;

  FOREACH v_codext IN ARRAY ARRAY['B3-4TLPG250UG4V', 'BAJAJVERDE'] LOOP
    IF v_codext = 'B3-4TLPG250UG4V' THEN
      v_claequ := 'Vehiculo'; v_codmod := v_modelo;
    ELSE
      v_claequ := 'Accesorio'; v_codmod := NULL;
    END IF;

    SELECT codequ, claequ, codmod INTO v_existente
    FROM public.equivalenciaproducto
    WHERE codpro = v_proveedor AND estequ AND upper(btrim(codext)) = upper(btrim(v_codext));
    IF FOUND THEN
      IF v_existente.claequ <> v_claequ OR v_existente.codmod IS DISTINCT FROM v_codmod THEN
        RAISE EXCEPTION 'La equivalencia activa % de Crosland ya existe con otra clasificación o modelo', v_codext;
      END IF;
    ELSE
      INSERT INTO public.equivalenciaproducto(codpro, codext, claequ, codmod, estequ, fueaprequ)
      VALUES (v_proveedor, v_codext, v_claequ, v_codmod, true, 'Product Owner HU-030 - 2026-10-24');
    END IF;
  END LOOP;
END
$semillas$;

