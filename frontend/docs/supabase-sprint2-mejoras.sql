-- Guardar o cambiar el modelo de un código de Crosland (un código nunca crea ni publica un modelo)
CREATE OR REPLACE FUNCTION public.hu030_guardar_equivalencia(p_codigo text, p_clasificacion text, p_codmod bigint DEFAULT NULL, p_observacion text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_codusu bigint := public.hu030_exigir_gestion();
  v_codpro bigint;
  v_codigo text := upper(btrim(coalesce(p_codigo, '')));
  v_codequ bigint;
BEGIN
  SELECT codpro INTO v_codpro FROM public.proveedor WHERE rucpro = '20502913752' AND estpro LIMIT 1;
  IF v_codpro IS NULL THEN RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'No está registrado Crosland como proveedor.'; END IF;
  IF v_codigo !~ '^[A-Z0-9][A-Z0-9._/-]{0,119}$' THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Escribe el código tal como sale en la factura (letras, números, guiones).';
  END IF;
  IF p_clasificacion NOT IN ('Vehiculo', 'Accesorio') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Indica si el código es una moto o un accesorio.';
  END IF;
  IF p_clasificacion = 'Vehiculo' AND NOT EXISTS (SELECT 1 FROM public.modelo WHERE codmod = p_codmod) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Elige el modelo de moto que corresponde a ese código.';
  END IF;
  SELECT codequ INTO v_codequ FROM public.equivalenciaproducto
  WHERE codpro = v_codpro AND upper(btrim(codext)) = v_codigo AND estequ FOR UPDATE;
  IF v_codequ IS NULL THEN
    INSERT INTO public.equivalenciaproducto (codpro, codext, claequ, codmod, estequ, fecaprequ, codusuapr, fueaprequ, obsequ)
    VALUES (v_codpro, v_codigo, p_clasificacion, CASE WHEN p_clasificacion = 'Vehiculo' THEN p_codmod END, true, now(), v_codusu,
      left('Panel EPSA · ' || coalesce(public.epsa_nombre_usuario(v_codusu), ''), 150), nullif(btrim(coalesce(p_observacion, '')), ''))
    RETURNING codequ INTO v_codequ;
  ELSE
    UPDATE public.equivalenciaproducto
    SET claequ = p_clasificacion, codmod = CASE WHEN p_clasificacion = 'Vehiculo' THEN p_codmod END, fecaprequ = now(), codusuapr = v_codusu,
        fueaprequ = left('Panel EPSA · ' || coalesce(public.epsa_nombre_usuario(v_codusu), ''), 150),
        obsequ = nullif(btrim(coalesce(p_observacion, '')), '')
    WHERE codequ = v_codequ;
  END IF;
  RETURN jsonb_build_object('codequ', v_codequ::text, 'codigo', v_codigo);
END;
$$;

