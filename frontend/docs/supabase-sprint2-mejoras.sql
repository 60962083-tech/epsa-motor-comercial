-- Última actualización de cada interesado visible (para Leads y Seguimiento)
CREATE OR REPLACE FUNCTION public.hu015_ultimas_actualizaciones()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE v_codusu bigint; v_rol text;
BEGIN
  SELECT p_codusu, p_rol INTO v_codusu, v_rol FROM public.hu015_rol_y_usuario();
  IF v_rol IS NULL OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Tu perfil no puede ver los interesados.';
  END IF;
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object('codlea', l.codlea::text, 'fecha', l.fecactlea, 'detalle', l.detactlea,
      'usuario', CASE WHEN l.codusuact IS NULL THEN NULL ELSE public.epsa_nombre_usuario(l.codusuact) END))
    FROM public.lead l
    WHERE l.fecactlea IS NOT NULL AND (v_rol IN ('Gerente', 'Administradora') OR l.codusu = v_codusu)
  ), '[]'::jsonb);
END;
$$;

-- Historial completo de un interesado, del cambio más reciente al más antiguo
CREATE OR REPLACE FUNCTION public.hu015_historial_lead(p_codlea bigint)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE v_codusu bigint; v_rol text; v_lead public.lead%ROWTYPE;
BEGIN
  SELECT p_codusu, p_rol INTO v_codusu, v_rol FROM public.hu015_rol_y_usuario();
  IF v_rol IS NULL OR v_rol NOT IN ('Gerente', 'Administradora', 'Vendedor') THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Tu perfil no puede ver este historial.';
  END IF;
  SELECT * INTO v_lead FROM public.lead WHERE codlea = p_codlea;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'Ese interesado ya no existe.';
  END IF;
  IF v_rol = 'Vendedor' AND v_lead.codusu IS DISTINCT FROM v_codusu
     AND NOT EXISTS (SELECT 1 FROM public.seguimientolead s WHERE s.codlea = p_codlea AND s.codusu = v_codusu) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Este interesado no está a tu cargo.';
  END IF;
  RETURN jsonb_build_object(
    'codlea', v_lead.codlea::text,
