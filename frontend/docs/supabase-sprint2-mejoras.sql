-- Al cambiar el estado o sus datos: queda en el historial y como última actualización
-- (el cambio de responsable lo registra la asignación, con su motivo)
CREATE OR REPLACE FUNCTION public.hu015_lead_cambio()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_usuario bigint := public.epsa_usuario_actual();
  v_campos text[] := ARRAY[]::text[];
  v_estado text;
  v_resumen text;
  v_codhle bigint;
BEGIN
  IF NEW.estlea IS DISTINCT FROM OLD.estlea THEN
    v_estado := public.hu015_etiqueta_estado(OLD.estlea) || ' → ' || public.hu015_etiqueta_estado(NEW.estlea);
    -- Si en la misma operación se registró un contacto, el cambio de estado va junto a él
    UPDATE public.historiallead SET estant = OLD.estlea, estnue = NEW.estlea
    WHERE codhle = (SELECT h.codhle FROM public.historiallead h
                    WHERE h.codlea = NEW.codlea AND h.fechle = now() AND h.codsle IS NOT NULL AND h.estnue IS NULL
                    ORDER BY h.codhle DESC LIMIT 1)
    RETURNING codhle INTO v_codhle;
    IF v_codhle IS NULL THEN
      INSERT INTO public.historiallead (codlea, codusu, tiphle, dethle, estant, estnue)
      VALUES (NEW.codlea, v_usuario, 'Cambio de estado', v_estado, OLD.estlea, NEW.estlea);
    END IF;
    v_resumen := 'Estado: ' || v_estado;
  END IF;

  IF NEW.nomlea IS DISTINCT FROM OLD.nomlea THEN v_campos := v_campos || 'nombre'::text; END IF;
  IF NEW.tellea IS DISTINCT FROM OLD.tellea THEN v_campos := v_campos || 'celular'::text; END IF;
  IF NEW.codmod IS DISTINCT FROM OLD.codmod THEN v_campos := v_campos || 'moto de interés'::text; END IF;
  IF NEW.collea IS DISTINCT FROM OLD.collea THEN v_campos := v_campos || 'color'::text; END IF;
  IF NEW.codsed IS DISTINCT FROM OLD.codsed THEN v_campos := v_campos || 'sede'::text; END IF;
  IF NEW.canlea IS DISTINCT FROM OLD.canlea THEN v_campos := v_campos || 'canal'::text; END IF;
  IF NEW.orilea IS DISTINCT FROM OLD.orilea THEN v_campos := v_campos || 'origen'::text; END IF;
  IF NEW.codcli IS DISTINCT FROM OLD.codcli THEN v_campos := v_campos || 'cliente'::text; END IF;
  IF NEW.obslea IS DISTINCT FROM OLD.obslea THEN v_campos := v_campos || 'observación'::text; END IF;
  IF cardinality(v_campos) > 0 THEN
    IF v_usuario IS NULL AND 'observación' = ANY (v_campos) THEN
      -- El mismo celular volvió a escribir desde la web: se guarda su nueva consulta (última línea)
      INSERT INTO public.historiallead (codlea, codusu, tiphle, dethle)
      VALUES (NEW.codlea, NULL, 'Nueva consulta web',
        left((string_to_array(NEW.obslea, E'\n'))[cardinality(string_to_array(NEW.obslea, E'\n'))], 500));
      v_resumen := concat_ws(' · ', v_resumen, 'Volvió a escribir desde la web');
    ELSE
      INSERT INTO public.historiallead (codlea, codusu, tiphle, dethle)
      VALUES (NEW.codlea, v_usuario, 'Datos actualizados', 'Cambió: ' || array_to_string(v_campos, ', '));
      v_resumen := concat_ws(' · ', v_resumen, 'Cambió: ' || array_to_string(v_campos, ', '));
    END IF;
  END IF;

  IF v_resumen IS NOT NULL THEN
    NEW.fecactlea := now();
    NEW.detactlea := left(v_resumen, 300);
    NEW.codusuact := v_usuario;
  END IF;
  RETURN NEW;
END;
$$;

-- Cada contacto o venta del seguimiento
CREATE OR REPLACE FUNCTION public.hu015_seguimiento_historial()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_tipo text := CASE WHEN NEW.tipsle = 'Venta' THEN 'Venta concretada' ELSE coalesce(NEW.tipsle, 'Contacto') END;
  v_codhle bigint;
  v_estado text;
BEGIN
  -- Si el estado cambió en la misma operación, se une a este contacto
  UPDATE public.historiallead
  SET tiphle = v_tipo, dethle = NEW.dessle, codusu = NEW.codusu, fecprohle = NEW.fecprosle, codsle = NEW.codsle, fechle = NEW.fecinisle
  WHERE codhle = (SELECT h.codhle FROM public.historiallead h
                  WHERE h.codlea = NEW.codlea AND h.fechle = now() AND h.tiphle = 'Cambio de estado' AND h.codsle IS NULL
                  ORDER BY h.codhle DESC LIMIT 1)
  RETURNING codhle, public.hu015_etiqueta_estado(estnue) INTO v_codhle, v_estado;
  IF v_codhle IS NULL THEN
    INSERT INTO public.historiallead (codlea, codusu, fechle, tiphle, dethle, fecprohle, codsle)
    VALUES (NEW.codlea, NEW.codusu, NEW.fecinisle, v_tipo, NEW.dessle, NEW.fecprosle, NEW.codsle)
    ON CONFLICT DO NOTHING;
  END IF;
  UPDATE public.lead
  SET fecactlea = NEW.fecinisle, codusuact = NEW.codusu,
      detactlea = left(CASE WHEN NEW.tipsle = 'Venta' THEN coalesce(NEW.dessle, 'Venta concretada')
                            ELSE concat_ws(' · ', v_tipo || ': ' || coalesce(NEW.dessle, ''), CASE WHEN v_estado IS NOT NULL THEN 'Queda ' || v_estado END) END, 300)
  WHERE codlea = NEW.codlea;
  RETURN NEW;
END;
$$;

-- Cada asignación o transferencia, con su motivo
CREATE OR REPLACE FUNCTION public.hu015_asignacion_historial()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_tipo text := CASE WHEN NEW.codusuant IS NULL THEN 'Asignación' ELSE 'Transferencia' END;
  v_texto text;
BEGIN
  v_texto := CASE WHEN NEW.codusuant IS NULL THEN 'Asignado a ' || public.epsa_nombre_usuario(NEW.codusunue)
                  ELSE 'Transferido de ' || public.epsa_nombre_usuario(NEW.codusuant) || ' a ' || public.epsa_nombre_usuario(NEW.codusunue) END
             || CASE WHEN nullif(btrim(NEW.motale), '') IS NOT NULL THEN '. Motivo: ' || btrim(NEW.motale) ELSE '' END;
  INSERT INTO public.historiallead (codlea, codusu, fechle, tiphle, dethle, codale)
  VALUES (NEW.codlea, NEW.codusuaut, NEW.fecale, v_tipo, v_texto, NEW.codale)
  ON CONFLICT DO NOTHING;
  UPDATE public.lead SET fecactlea = NEW.fecale, codusuact = NEW.codusuaut, detactlea = left(v_texto, 300)
  WHERE codlea = NEW.codlea;
  RETURN NEW;
END;
$$;

