-- Factura subida desde el panel: guarda dónde quedaron su XML y PDF y quién la subió
CREATE OR REPLACE FUNCTION public.hu030_registrar_subida_panel(p_coddoc bigint, p_rutaxml text, p_sha256xml text, p_rutapdf text DEFAULT NULL, p_sha256pdf text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_codusu bigint := public.hu030_exigir_gestion();
  v_doc public.documentocompra%ROWTYPE;
BEGIN
  SELECT * INTO v_doc FROM public.documentocompra WHERE coddoc = p_coddoc FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'PT404', MESSAGE = 'Esa factura no existe.'; END IF;
  IF p_rutaxml IS NOT NULL AND (p_rutaxml !~ '^panel/[0-9a-f]{64}/factura\.xml$' OR lower(coalesce(v_doc.sha256xml, '')) <> lower(coalesce(p_sha256xml, ''))) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El XML guardado no corresponde a esta factura.';
  END IF;
  IF p_rutapdf IS NOT NULL AND (p_rutapdf !~ '^panel/[0-9a-f]{64}/factura\.pdf$' OR coalesce(p_sha256pdf, '') !~ '^[0-9a-f]{64}$') THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'El PDF guardado no es válido.';
  END IF;
  UPDATE public.documentocompra
  SET rutaxml = coalesce(rutaxml, p_rutaxml),
      rutapdf = coalesce(rutapdf, p_rutapdf),
      sha256pdf = CASE WHEN rutapdf IS NULL AND p_rutapdf IS NOT NULL THEN p_sha256pdf ELSE sha256pdf END,
      pdfpendiente = CASE WHEN coalesce(rutapdf, p_rutapdf) IS NOT NULL THEN false ELSE pdfpendiente END
  WHERE coddoc = p_coddoc;
  -- El intento recién hecho desde el panel queda a nombre de quien subió la factura
  UPDATE public.intentodocumento SET tipactor = 'Usuario', codusu = v_codusu
  WHERE codint = (SELECT i.codint FROM public.intentodocumento i
                  WHERE i.coddoc = p_coddoc AND i.tipactor = 'Automatico' AND i.fecinicio > now() - interval '10 minutes'
                  ORDER BY i.codint DESC LIMIT 1);
  RETURN jsonb_build_object('coddoc', p_coddoc::text);
END;
$$;

