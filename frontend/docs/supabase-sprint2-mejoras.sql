-- Todo traslado nuevo (en tránsito) debe traer su motivo: «Motivo: <motivo>» o «Motivo: <motivo> · Detalle: <texto>»
CREATE OR REPLACE FUNCTION public.hu003_validar_motivo_traslado()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE
  v_texto text := btrim(coalesce(NEW.obsmub, ''));
  v_motivo public.motivotraslado%ROWTYPE;
  v_prefijo text;
  v_detalle text;
BEGIN
  IF NEW.estmub NOT IN ('Pendiente', 'En transito') THEN
    RETURN NEW;
  END IF;
  SELECT * INTO v_motivo FROM public.motivotraslado m
  WHERE m.estmtr AND (v_texto = 'Motivo: ' || m.nommtr OR left(v_texto, char_length('Motivo: ' || m.nommtr || ' · Detalle: ')) = 'Motivo: ' || m.nommtr || ' · Detalle: ')
  ORDER BY char_length(m.nommtr) DESC
  LIMIT 1;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Elige el motivo del traslado.';
  END IF;
  v_prefijo := 'Motivo: ' || v_motivo.nommtr || ' · Detalle: ';
  IF left(v_texto, char_length(v_prefijo)) = v_prefijo THEN
    v_detalle := nullif(btrim(substr(v_texto, char_length(v_prefijo) + 1)), '');
  END IF;
  IF v_motivo.detoblmtr AND (v_detalle IS NULL OR char_length(v_detalle) < 5) THEN
    RAISE EXCEPTION USING ERRCODE = 'PT400', MESSAGE = 'Escribe el detalle del motivo del traslado.';
  END IF;
  NEW.codmtr := v_motivo.codmtr;
  NEW.detmub := left(v_detalle, 450);
  RETURN NEW;
END;
$$;

